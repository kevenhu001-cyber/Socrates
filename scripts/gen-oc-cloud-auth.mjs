// gen-oc-cloud-auth.mjs — snapshot OpenConnector provider auth metadata for
// OOMOL-cloud mode.
//
// Socrates must not import open-connector/ at runtime (see AGENTS.md: nothing
// in frontend/src or server/src imports it). This codegen runs once per
// vendored-tree update and writes a Socrates-owned static snapshot that the
// catalog uses when the local sidecar is down but OOMOL_PROJECT_API_KEY is
// configured (users who provisioned providers in the OOMOL cloud console).
//
// It reads provider definition.ts files as DATA (via tsx) and keeps only
// JSON-safe auth metadata: authTypes + credential field descriptors.
//
// Usage (from repo root):
//   ./server/node_modules/.bin/tsx scripts/gen-oc-cloud-auth.mjs
// Output:
//   server/src/services/openConnectorCloudAuth.generated.ts

import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const inventoryUrl = pathToFileURL(resolve(rootDir, 'server/src/services/openConnectorAppInventory.ts')).href;
const providersDir = resolve(rootDir, 'open-connector/src/providers');
const outFile = resolve(rootDir, 'server/src/services/openConnectorCloudAuth.generated.ts');

const FIELD_KEYS = ['key', 'label', 'inputType', 'secret', 'required', 'placeholder', 'description'];
const AUTH_KEYS = ['type', 'label', 'placeholder', 'description', 'fields'];

function pick(obj, keys) {
  const out = {};
  if (!obj || typeof obj !== 'object') return out;
  for (const k of keys) {
    const v = obj[k];
    if (v === undefined) continue;
    if (typeof v === 'string' || typeof v === 'boolean') out[k] = v;
  }
  return out;
}

function sanitizeAuth(auth) {
  if (!Array.isArray(auth)) return [];
  return auth.map((entry) => {
    const base = pick(entry, AUTH_KEYS);
    delete base.fields;
    if (Array.isArray(entry.fields)) {
      base.fields = entry.fields.map((f) => pick(f, FIELD_KEYS)).filter((f) => typeof f.key === 'string');
    }
    return base;
  });
}

const inventory = await import(inventoryUrl);
const services = [...new Set(
  inventory.OPEN_CONNECTOR_APP_INVENTORY.filter((e) => e.status === 'ready' && e.ocService).map((e) => e.ocService),
)].sort();

const missing = services.filter((s) => !readdirSync(providersDir, { withFileTypes: true }).some((d) => d.isDirectory() && d.name === s));
if (missing.length > 0) {
  console.error(`[gen-oc-cloud-auth] missing provider dirs: ${missing.join(', ')}`);
  process.exit(1);
}

const entries = [];
for (const service of services) {
  const mod = await import(pathToFileURL(resolve(providersDir, service, 'definition.ts')).href);
  const provider = mod.provider;
  if (!provider || provider.service !== service) {
    console.error(`[gen-oc-cloud-auth] bad export in ${service}/definition.ts`);
    process.exit(1);
  }
  entries.push([service, {
    authTypes: Array.isArray(provider.authTypes) ? provider.authTypes.filter((t) => typeof t === 'string') : [],
    auth: sanitizeAuth(provider.auth),
    categories: Array.isArray(provider.categories) ? provider.categories.filter((t) => typeof t === 'string') : [],
    actionCount: Array.isArray(provider.actions) ? provider.actions.length : 0,
  }]);
}

const body = `/* GENERATED by scripts/gen-oc-cloud-auth.mjs — DO NOT EDIT.
 *
 * Static snapshot of open-connector provider auth metadata for OOMOL-cloud
 * mode (sidecar down, OOMOL_PROJECT_API_KEY configured). Regenerate after
 * updating the vendored open-connector tree:
 *   ./server/node_modules/.bin/tsx scripts/gen-oc-cloud-auth.mjs
 */

export interface CloudAuthField {
  key: string;
  label?: string;
  inputType?: string;
  secret?: boolean;
  required?: boolean;
  placeholder?: string;
  description?: string;
}

export interface CloudAuthConfig {
  type: string;
  label?: string;
  placeholder?: string;
  description?: string;
  fields?: CloudAuthField[];
}

export interface CloudAuthMeta {
  authTypes: string[];
  auth: CloudAuthConfig[];
  categories: string[];
  actionCount: number;
}

/** Auth metadata per ocService (stable ids, no runtime open-connector import). */
export const OPEN_CONNECTOR_CLOUD_AUTH: Record<string, CloudAuthMeta> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};
`;

writeFileSync(outFile, body);
console.log(`[gen-oc-cloud-auth] wrote ${outFile} (${entries.length} services)`);
