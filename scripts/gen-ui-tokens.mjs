#!/usr/bin/env node
// scripts/gen-ui-tokens.mjs — project packages/theme/src/ui.ts into CSS.
//
// packages/theme is the single source for the new UI tokens. This script
// writes frontend/src/styles/foundations/tokens.generated.css, which
// themes.css imports, so the web shell and the React Native primitives in
// packages/ui read the same values.
//
// Usage:
//   node --experimental-strip-types scripts/gen-ui-tokens.mjs          write
//   node --experimental-strip-types scripts/gen-ui-tokens.mjs --check  fail if stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = `${ROOT}frontend/src/styles/foundations/tokens.generated.css`;
const CHECK = process.argv.includes('--check');

const { uiColors, uiColorVar, uiFont, uiType, uiRadius, uiSpace, uiShadow, uiMotion } = await import(
  new URL('../packages/theme/src/ui.ts', import.meta.url).href
);

const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const px = (n) => (n === 0 ? '0' : `${n}px`);

function block(selector, entries) {
  return `${selector} {\n${entries.map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`;
}

const root = [
  ['--ui-font-ui', uiFont.sans],
  ['--ui-font-ui-mono', uiFont.mono],
];
for (const [name, step] of Object.entries(uiType)) {
  const key = kebab(name);
  root.push([`--ui-type-${key}-size`, px(step.size)]);
  root.push([`--ui-type-${key}-line`, px(step.lineHeight)]);
  root.push([`--ui-type-${key}-weight`, step.weight]);
  root.push([`--ui-type-${key}-tracking`, px(step.tracking)]);
}
for (const [name, value] of Object.entries(uiRadius)) {
  if (name === 'card') root.push(['--ui-radius-card', px(value)]);
  else root.push([`--ui-round-${name}`, px(value)]);
}
for (const [name, value] of Object.entries(uiSpace)) root.push([`--ui-gap-${name}`, px(value)]);
root.push(['--ui-motion-fast', `${uiMotion.fast}ms`]);
root.push(['--ui-motion-medium', `${uiMotion.medium}ms`]);
root.push(['--ui-motion-enter', `${uiMotion.enter}ms`]);
root.push(['--ui-motion-ease-out', uiMotion.easeOut]);

function modeEntries(mode) {
  const entries = Object.entries(uiColors[mode]).map(([role, value]) => [uiColorVar[role], value]);
  for (const [name, value] of Object.entries(uiShadow[mode])) entries.push([`--ui-elevation-${name}`, value]);
  return entries;
}

const css = [
  '/*',
  ' * tokens.generated.css — GENERATED by scripts/gen-ui-tokens.mjs from',
  ' * packages/theme/src/ui.ts. Do not edit by hand; change the source and run',
  ' *   node --experimental-strip-types scripts/gen-ui-tokens.mjs',
  ' * themes.css imports this file. Existing --ui-* names stay owned by',
  ' * tokens.css / themes.css; this file only adds the new UI vocabulary.',
  ' */',
  '',
  block(':root', root),
  block('[data-mode="light"]', modeEntries('light')),
  block('[data-mode="dark"]', modeEntries('dark')).trimEnd(),
  '',
].join('\n');

if (CHECK) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== css) {
    console.error('[gen-ui-tokens] tokens.generated.css is stale — run: node --experimental-strip-types scripts/gen-ui-tokens.mjs');
    process.exit(1);
  }
  console.log('[gen-ui-tokens] OK — generated CSS matches packages/theme.');
} else {
  writeFileSync(OUT, css);
  console.log(`[gen-ui-tokens] wrote ${OUT.replace(ROOT, '')}`);
}
